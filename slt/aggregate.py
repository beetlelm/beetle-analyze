"""Aggregate per-rank SLT shards into a single ledger and emit LaTeX.

Three jobs:

  1. Merge per-rank CSV shards under ``<output_root>/slt/`` into one
     consolidated ledger per stage (``llc_summary.csv``,
     ``susceptibilities_summary.csv``, etc.).
  2. Emit ``<paper_root>/numbers.tex`` — one ``\\newcommand`` per
     headline statistic (PC1 for the multi mean, A1 r, A2a/A2b deltas,
     etc.) so the LaTeX document auto-fills as the run progresses.
  3. Emit ``<paper_root>/tables/main.tex`` — the per-cell table with
     λ̂, PC1, effective rank, capacity score, regime.

Run order: invoke after every stage completes, or once at the end.
"""

from __future__ import annotations

import argparse
import csv
import json
import logging
import os
import sys
from collections import defaultdict
from pathlib import Path
from typing import Optional

import numpy as np

_THIS = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(_THIS))

log = logging.getLogger(__name__)


def _merge_rank_shards(slt_dir: Path, prefix: str, out_name: str) -> Path | None:
    """Concatenate ``<prefix>.rank*.csv`` files into ``<out_name>.csv``."""
    shards = sorted(slt_dir.glob(f"{prefix}.rank*.csv"))
    if not shards:
        return None
    rows: list[dict] = []
    fieldnames: list[str] = []
    for shard in shards:
        with shard.open() as fh:
            reader = csv.DictReader(fh)
            if reader.fieldnames and not fieldnames:
                fieldnames = list(reader.fieldnames)
            for row in reader:
                rows.append(row)
    if not rows:
        return None
    out_path = slt_dir / out_name
    with out_path.open("w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=fieldnames)
        w.writeheader()
        for row in rows:
            w.writerow(row)
    log.info("[aggregate] merged %d shards (%d rows) → %s",
             len(shards), len(rows), out_path.name)
    return out_path


def _read_csv_rows(path: Path) -> list[dict]:
    if not path.exists():
        return []
    with path.open() as fh:
        return list(csv.DictReader(fh))


def _safe_float(s: str | None, default: float = float("nan")) -> float:
    try:
        return float(s) if s not in (None, "") else default
    except ValueError:
        return default


def _mean_by_regime(rows: list[dict], col: str) -> dict[str, float]:
    bucket: dict[str, list[float]] = defaultdict(list)
    for r in rows:
        v = _safe_float(r.get(col))
        if not np.isnan(v):
            bucket[r.get("regime", "unknown")].append(v)
    return {k: float(np.mean(v)) for k, v in bucket.items() if v}


def _format_cmd(name: str, value: str) -> str:
    """Emit a LaTeX ``\\newcommand`` line."""
    return f"\\newcommand{{\\{name}}}{{{value}}}\n"


def _format_num(x: float, digits: int = 3) -> str:
    if x is None or (isinstance(x, float) and (np.isnan(x) or np.isinf(x))):
        return r"\PLACEHOLDER{}"
    return f"{x:.{digits}f}"


def write_numbers_tex(slt_dir: Path, paper_dir: Path) -> None:
    """Write paper/numbers.tex with all auto-filled statistics."""
    paper_dir.mkdir(parents=True, exist_ok=True)
    lines: list[str] = ["% AUTO-GENERATED by slt.aggregate — do not hand-edit.\n"]

    # LLC means by regime.
    llc_rows = _read_csv_rows(slt_dir / "llc_summary.csv")
    llc_by_regime = _mean_by_regime(llc_rows, "llc_mean")
    for regime in ("mono", "bi", "multi"):
        v = llc_by_regime.get(regime, float("nan"))
        lines.append(_format_cmd(f"LLCmean{regime.capitalize()}", _format_num(v)))
    lines.append(_format_cmd("NCells", str(len(llc_rows))))

    # Susceptibility PC1 by regime.
    sus_rows = _read_csv_rows(slt_dir / "susceptibilities_summary.csv")
    pc1_by_regime = _mean_by_regime(sus_rows, "pc1_var_ratio")
    for regime in ("mono", "bi", "multi"):
        v = pc1_by_regime.get(regime, float("nan"))
        pct = v * 100 if not np.isnan(v) else v
        lines.append(_format_cmd(f"PCone{regime.capitalize()}", _format_num(pct, 1)))

    rank99_by_regime = _mean_by_regime(sus_rows, "matrix_rank_99pct")
    for regime in ("mono", "bi", "multi"):
        v = rank99_by_regime.get(regime, float("nan"))
        lines.append(_format_cmd(f"RankNN{regime.capitalize()}",
                                 _format_num(v, 1)))

    # Bridge regression (A1).
    bridge_path = slt_dir / "bridge_regression.json"
    if bridge_path.exists():
        try:
            j = json.loads(bridge_path.read_text())
            lines.append(_format_cmd("BridgeR", _format_num(j.get("pearson_r", float("nan")))))
            lines.append(_format_cmd("BridgeP", _format_num(j.get("p_value", float("nan")))))
            lines.append(_format_cmd("BridgeN", str(j.get("n", 0))))
            lines.append(_format_cmd("BridgePass",
                                     "Yes" if j.get("pass_criterion_r_gt_0_7") else "No"))
        except Exception:
            pass

    # Falsification (A2).
    fals_rows = _read_csv_rows(slt_dir / "falsification_summary.csv")
    a2a = [r for r in fals_rows if r.get("kind") == "a2a_disjoint"]
    a2b_before = [r for r in fals_rows if r.get("kind") == "a2b_permuted_before"]
    a2b_after = [r for r in fals_rows if r.get("kind") == "a2b_permuted_after"]
    if a2a:
        v = float(np.mean([_safe_float(r["llc_mean"]) for r in a2a]))
        lines.append(_format_cmd("LLCAtwoa", _format_num(v)))
    if a2b_before and a2b_after:
        b = float(np.mean([_safe_float(r["llc_mean"]) for r in a2b_before]))
        a = float(np.mean([_safe_float(r["llc_mean"]) for r in a2b_after]))
        lines.append(_format_cmd("LLCAtwobBefore", _format_num(b)))
        lines.append(_format_cmd("LLCAtwobAfter", _format_num(a)))
        lines.append(_format_cmd("LLCAtwobDelta", _format_num(a - b)))

    # β-sweep (S2).
    beta_rows = _read_csv_rows(slt_dir / "beta_sweep_summary.csv")
    if beta_rows:
        worst = max(_safe_float(r.get("rel_err_default_vs_ti")) for r in beta_rows)
        lines.append(_format_cmd("BetaWorstRelErr", _format_num(worst * 100, 2)))
        passes = sum(1 for r in beta_rows if r.get("passes_10pct") in ("True", True, "1"))
        lines.append(_format_cmd("BetaPassFrac", f"{passes}/{len(beta_rows)}"))

    out_path = paper_dir / "numbers.tex"
    out_path.write_text("".join(lines))
    log.info("[aggregate] wrote %s (%d macros)", out_path, len(lines) - 1)


def write_main_table(slt_dir: Path, paper_dir: Path) -> None:
    """Write paper/tables/main.tex — per-cell λ̂ × PC1 × rank table."""
    llc_rows = _read_csv_rows(slt_dir / "llc_summary.csv")
    sus_rows = _read_csv_rows(slt_dir / "susceptibilities_summary.csv")
    sus_by_key = {(r["repo"], r["revision"]): r for r in sus_rows}

    rows: list[tuple[str, str, str, str, str, str, str]] = []
    for r in llc_rows:
        key = (r["repo"], r["revision"])
        s = sus_by_key.get(key, {})
        rows.append((
            r.get("regime", "?"),
            r["repo"].split("/")[-1][:24],
            r["revision"],
            _format_num(_safe_float(r.get("llc_mean")), 3),
            _format_num(_safe_float(r.get("llc_std")), 3),
            _format_num(_safe_float(s.get("pc1_var_ratio")) * 100, 1) if s else r"\PLACEHOLDER{}",
            _format_num(_safe_float(s.get("matrix_rank_99pct")), 0) if s else r"\PLACEHOLDER{}",
        ))

    paper_dir.mkdir(parents=True, exist_ok=True)
    table_dir = paper_dir / "tables"
    table_dir.mkdir(exist_ok=True)
    out_path = table_dir / "main.tex"

    body = "\n".join(
        f"  {regime} & {repo} & {rev} & ${llc} \\pm {std}$ & {pc1} & {rk} \\\\"
        for regime, repo, rev, llc, std, pc1, rk in rows
    )
    tex = (
        "% AUTO-GENERATED by slt.aggregate — do not hand-edit.\n"
        "\\begin{tabular}{llrrrr}\n"
        "  \\toprule\n"
        "  Regime & Model & Ckpt & $\\hat\\lambda$ & PC1 (\\%) & rank$_{99\\%}$ \\\\\n"
        "  \\midrule\n"
        f"{body}\n"
        "  \\bottomrule\n"
        "\\end{tabular}\n"
    )
    out_path.write_text(tex)
    log.info("[aggregate] wrote %s (%d rows)", out_path, len(rows))


def aggregate_all(output_root: Path, paper_dir: Path) -> None:
    slt_dir = output_root / "slt"
    if not slt_dir.exists():
        log.warning("[aggregate] no slt/ dir at %s", slt_dir)
        return

    for prefix, out in [
        ("llc_summary", "llc_summary.csv"),
        ("susceptibilities_summary", "susceptibilities_summary.csv"),
        ("fisher_summary", "fisher_summary.csv"),
        ("falsification_summary", "falsification_summary.csv"),
        ("per_language_llc_summary", "per_language_llc_summary.csv"),
        ("beta_sweep_summary", "beta_sweep_summary.csv"),
    ]:
        _merge_rank_shards(slt_dir, prefix, out)

    write_numbers_tex(slt_dir, paper_dir)
    write_main_table(slt_dir, paper_dir)


def run_stage(args) -> None:
    if int(getattr(args, "rank", 0)) != 0:
        return
    paper_dir = getattr(args, "paper_dir", None) or (
        Path(__file__).resolve().parent / "paper"
    )
    aggregate_all(args.output_root, Path(paper_dir))


def main(argv: Optional[list[str]] = None) -> int:
    p = argparse.ArgumentParser(description="Aggregate SLT shards → numbers.tex.")
    p.add_argument("--output-root", type=Path, default=Path("results"))
    p.add_argument(
        "--paper-dir", type=Path,
        default=Path(__file__).resolve().parent / "paper",
    )
    p.add_argument("--check-references", action="store_true",
                   help="Sanity-check pico-tiny LLC against the known reference range.")
    args = p.parse_args(argv)
    logging.basicConfig(level=logging.INFO, format="%(asctime)s [%(levelname)s] %(message)s")
    aggregate_all(args.output_root, args.paper_dir)
    if args.check_references:
        slt_dir = args.output_root / "slt"
        rows = _read_csv_rows(slt_dir / "llc_summary.csv")
        for r in rows:
            if "pico-decoder-tiny" in r.get("repo", ""):
                v = _safe_float(r.get("llc_mean"))
                ok = 30.0 < v < 400.0
                print(f"  pico-tiny λ̂ = {v:.2f}  (reference 50–200, accept 30–400): {'OK' if ok else 'OUT OF RANGE'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
